import type { CfdEvidencePayload, ManuscriptPayload, ReferenceRecord } from '@aeroscribe/contract';
import type { JournalTarget } from '@aeroscribe/pipeline';
import { sha256 } from '../lib/canonical';
import { bibliographyFrom, citationText } from './bibliography';
import { escapeLatex, stripLatex } from './escape';
import { cfdFigure, type Figure, type FigureFile, type FigureProvenance } from './figures';

/**
 * Turn a stored manuscript record into a LaTeX project.
 *
 * What this renders is exactly what the registry holds: no prose is rewritten,
 * no number is recalculated and no citation is completed from memory. If a
 * section body says `0.4264`, the `.tex` says `0.4264`.
 *
 * The output is deterministic — same record in, byte-identical files out — which
 * is why the header carries the manuscript's own `generatedAt` rather than the
 * wall clock. Regenerating a run must not produce a diff.
 */

/** Templates this renderer actually knows how to produce. */
export const TEMPLATES = {
  'aiaa-tc (AIAA technical paper)': 'aiaa-style',
  'elsarticle-num': 'elsevier-style',
} as const;

export type TemplateId = (typeof TEMPLATES)[keyof typeof TEMPLATES];

export function templateIdFor(journal: JournalTarget): TemplateId {
  const id = TEMPLATES[journal.latexTemplate as keyof typeof TEMPLATES];
  if (!id) {
    // A new journal entry with a template we cannot produce is a configuration
    // bug; guessing a layout would hide it in a PDF nobody checked.
    throw new Error(
      `no LaTeX template for "${journal.latexTemplate}" (journal ${journal.id}); known templates: ${Object.keys(
        TEMPLATES,
      ).join(', ')}`,
    );
  }
  return id;
}

export interface RenderInput {
  runId: string;
  manuscript: ManuscriptPayload;
  journal: JournalTarget;
  /** The run's CFD evidence, for the study figure; `null` when there is none. */
  cfd: CfdEvidencePayload | null;
  /** SHA-256 of each input payload, written into the header for provenance. */
  inputHashes: ReadonlyArray<{ kind: string; seq: number; sha256: string }>;
}

export interface RenderedManuscript {
  template: TemplateId;
  /** The complete `.tex` file. */
  tex: string;
  texSha256: string;
  /** Text artefacts, including `manuscript.tex` itself. */
  files: Array<{ name: string; content: string }>;
  /**
   * The body of the document: abstract and section text, between the verifiable
   * markers. Claim verification runs on this, never on the preamble.
   *
   * A figure is a separate `\input` file, so its caption is not inside this
   * span. That is deliberate: the caption states provenance (a record number and
   * a SHA-256), and a hexadecimal digest is not a quantitative claim an evidence
   * record can back. The figure files are hashed into the render record, which
   * is where their contents are checked.
   */
  verifiableSource: string;
  /** `stripLatex(verifiableSource)` — what the claim verifier reads. */
  verifiableText: string;
  missingBibliographyFields: string[];
  figure: FigureFile | null;
}

const BEGIN_MARK = '% ==== verifiable text begins: abstract, sections, captions ====';
const END_MARK = '% ==== verifiable text ends ====';

function preamble(template: TemplateId, journal: JournalTarget): string {
  // Both templates are built on `article`: the publisher classes are not
  // shipped with TeX Live, and a package that silently substitutes a lookalike
  // class would be a claim the PDF cannot support. The record names the
  // template that was used.
  const common = [
    '\\documentclass[11pt]{article}',
    '\\usepackage[margin=1in]{geometry}',
    '\\usepackage{amsmath,amssymb,booktabs,graphicx}',
    '\\usepackage{pgfplots}',
    '\\usepgfplotslibrary{groupplots}',
    '\\pgfplotsset{compat=1.18}',
  ];
  if (template === 'elsevier-style') {
    return [...common, '% Elsevier-style layout on the standard article class.'].join('\n');
  }
  return [
    ...common,
    '% AIAA-style layout on the standard article class: single column, numbered',
    "% references, no publisher class file. Check the target journal's current",
    `% guidelines before submission (template recorded as "${journal.latexTemplate}").`,
  ].join('\n');
}

function header(input: RenderInput, template: TemplateId): string {
  return [
    '% Generated by @aeroscribe/api — do not edit: regenerate the manuscript record.',
    `% run: ${escapeLatex(input.runId)}`,
    `% journal: ${escapeLatex(input.journal.name)} (${escapeLatex(input.journal.id)})`,
    `% template: ${template}`,
    `% manuscript generated_at: ${input.manuscript.generatedAt}`,
    ...input.inputHashes.map((hash) => `% input ${hash.kind} #${hash.seq}: sha256=${hash.sha256}`),
  ].join('\n');
}

/**
 * The study figure, bound to the record it came from.
 *
 * The provenance comes from the same hash list the header prints, so the figure
 * and the document cannot name different evidence for the same numbers. A
 * manuscript whose `cfd` payload has no `cfd-run` hash beside it is a wiring
 * bug, and `cfdFigure` refuses rather than plot numbers with no origin.
 */
function buildFigure(input: RenderInput): Figure | null {
  if (!input.cfd) return null;
  const record = input.inputHashes.find((hash) => hash.kind === 'cfd-run');
  const provenance: FigureProvenance | null = record
    ? { runId: input.runId, seq: record.seq, payloadHash: record.sha256 }
    : null;
  return cfdFigure(input.cfd, provenance);
}

/** Render the manuscript. Throws when the journal's template is unknown. */
export function renderManuscript(input: RenderInput): RenderedManuscript {
  const { manuscript, journal } = input;
  const template = templateIdFor(journal);
  const bibliography = bibliographyFrom(manuscript.references.map((line) => line.record));
  const figure = buildFigure(input);

  const body = [
    BEGIN_MARK,
    `\\title{${escapeLatex(manuscript.title)}}`,
    '\\author{AeroScribe (automated writing system)}',
    '\\date{}',
    '\\maketitle',
    '\\begin{abstract}',
    escapeLatex(manuscript.abstract),
    '\\end{abstract}',
    ...manuscript.sections.flatMap((section) => [
      `\\section{${escapeLatex(section.heading)}}`,
      escapeLatex(section.body),
      '',
    ]),
    ...(figure ? [`\\input{${figure.tex.name}}`, ''] : []),
    END_MARK,
    ...(manuscript.references.length === 0
      ? []
      : [
          // The bibliography is inline: the document then compiles with two
          // `pdflatex` passes and no BibTeX run, and `references.bib` is still
          // written for the journal's own pipeline.
          `\\begin{thebibliography}{${Math.max(manuscript.references.length, 9)}}`,
          ...manuscript.references.map(
            (line) => `\\bibitem{${line.record.key}} ${citationText(line.record)}`,
          ),
          '\\end{thebibliography}',
          '',
        ]),
  ].join('\n');

  const tex = [
    header(input, template),
    preamble(template, journal),
    '',
    '\\begin{document}',
    body,
    '\\end{document}',
    '',
  ].join('\n');

  const verifiableSource = body.slice(
    body.indexOf(BEGIN_MARK) + BEGIN_MARK.length,
    body.lastIndexOf(END_MARK),
  );

  const files: Array<{ name: string; content: string }> = [
    { name: 'manuscript.tex', content: tex },
    { name: 'references.bib', content: bibliography.bib },
    ...(figure ? [figure.tex, ...figure.dat] : []),
  ];

  return {
    template,
    tex,
    texSha256: sha256(tex),
    files,
    verifiableSource,
    verifiableText: stripLatex(verifiableSource),
    missingBibliographyFields: bibliography.missing,
    figure: figure?.tex ?? null,
  };
}

/** The structured records behind a manuscript's rendered reference list. */
export function referencesOf(manuscript: ManuscriptPayload): ReferenceRecord[] {
  return manuscript.references.map((line) => line.record);
}
