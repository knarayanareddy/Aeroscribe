import { formatNumber } from '@aeroscribe/pipeline';
import { useMemo, useState } from 'react';
import { manuscriptSectionsRun002, mockPipelineRuns } from '../data/mockData';
import { usePipeline } from '../state/pipelineContext';
import ManuscriptLive from './ManuscriptLive';

const TARGET_WORDS = 10_000;
const REFERENCE_COUNT = 68;

const statusStyles: Record<string, string> = {
  complete: 'bg-emerald-100 text-emerald-700',
  in_review: 'bg-orange-100 text-orange-700',
  draft: 'bg-slate-100 text-slate-600',
  pending: 'bg-slate-100 text-slate-400',
};

const statusIcons: Record<string, string> = {
  complete: '✓',
  in_review: '⌛',
  draft: '✏',
  pending: '·',
};

/** Escape the characters LaTeX treats as markup. */
function escapeLatex(value: string): string {
  return value
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/([%&$#_{}])/g, '\\$1')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/\^/g, '\\textasciicircum{}');
}

function buildLatex(title: string, abstract: string): string {
  return `\\documentclass[conf]{aiaa-tc}
\\usepackage{amsmath,amssymb,graphicx,booktabs}

\\title{${escapeLatex(title)}}

\\begin{document}
\\maketitle

\\begin{abstract}
${escapeLatex(abstract)}
\\end{abstract}

\\section{Introduction}
% Content is generated by SectionWriterAgent from registry-backed evidence.

\\section{Computational Methodology}
% Grid convergence and solver settings are attached from the evidence registry.

\\section{Results}
% Every quantitative claim must render as: value \\pm uncertainty (confidence, method).

\\section{Conclusions}

\\bibliography{references}
\\end{document}
`;
}

export default function ManuscriptView() {
  const [activeSectionId, setActiveSectionId] = useState(manuscriptSectionsRun002[0]?.id ?? '');
  const [showLatex, setShowLatex] = useState(false);
  const [notice, setNotice] = useState<string | null>(null);

  const { mode } = usePipeline();

  const run = mockPipelineRuns.find((candidate) => candidate.id === 'run-002');
  const sections = manuscriptSectionsRun002;
  const activeSection = sections.find((section) => section.id === activeSectionId) ?? sections[0];

  const totalWords = sections.reduce((total, section) => total + section.wordCount, 0);
  const progress = Math.min(Math.round((totalWords / TARGET_WORDS) * 100), 100);

  const latex = useMemo(
    () =>
      buildLatex(
        run?.paperTitle ?? 'Untitled manuscript',
        sections.find((section) => section.id === 'abstract')?.content ?? '',
      ),
    [run?.paperTitle, sections],
  );

  // Live mode: the API's manuscript, or a notice. Never this fixture document.
  // The branch sits after every hook so the hook order never changes.
  if (mode === 'live') return <ManuscriptLive />;

  const abstractWords = sections.find((section) => section.id === 'abstract')?.wordCount ?? 0;
  const uncertaintyCount = sections
    .map((section) => section.content ?? '')
    .join(' ')
    .match(/±/g)?.length;

  const compliance = [
    {
      label: 'Abstract ≤ 250 words',
      ok: abstractWords > 0 && abstractWords <= 250,
      detail: `${abstractWords} words`,
    },
    {
      label: 'All sections have content',
      ok: sections.every((section) => Boolean(section.content)),
      detail: `${sections.filter((section) => section.content).length}/${sections.length}`,
    },
    {
      label: 'References section present',
      ok: sections.some((section) => section.id === 'references'),
      detail: `${REFERENCE_COUNT} refs in fixture`,
    },
    {
      label: 'Values carry ± uncertainty',
      ok: (uncertaintyCount ?? 0) > 0,
      detail: `${uncertaintyCount ?? 0} values`,
    },
    {
      label: 'AI-usage disclosure statement',
      ok: false,
      detail: 'not in fixture',
    },
  ];

  const copyLatex = async () => {
    try {
      await navigator.clipboard.writeText(latex);
      setNotice('LaTeX source copied to the clipboard.');
    } catch {
      setNotice('Clipboard access was blocked by the browser. Select the source manually instead.');
    }
  };

  const downloadLatex = () => {
    const blob = new Blob([latex], { type: 'application/x-tex' });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = 'manuscript.tex';
    anchor.click();
    URL.revokeObjectURL(url);
    setNotice('manuscript.tex downloaded.');
  };

  return (
    <div className="space-y-6 p-4 sm:p-6 lg:p-8">
      <div className="flex flex-wrap items-start justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-slate-900">Manuscript synthesis</h1>
          <p className="mt-1 text-slate-500">
            AIAA LaTeX export · fixture manuscript for run-002 · no backend
          </p>
        </div>
        <div className="flex flex-wrap gap-2">
          <button
            type="button"
            onClick={() => setShowLatex((current) => !current)}
            aria-expanded={showLatex}
            className="flex items-center gap-2 rounded-lg border border-slate-200 px-4 py-2.5 text-sm font-medium text-slate-600 transition-colors hover:bg-slate-50"
          >
            <span className="font-mono text-xs">LaTeX</span>
            {showLatex ? 'Hide source' : 'View source'}
          </button>
          <button
            type="button"
            onClick={() => window.print()}
            className="rounded-lg bg-blue-600 px-4 py-2.5 text-sm font-semibold text-white transition-colors hover:bg-blue-700"
          >
            Print / save as PDF
          </button>
        </div>
      </div>

      {notice && (
        <p
          role="status"
          className="rounded-lg border border-blue-100 bg-blue-50 px-4 py-2 text-sm text-blue-800"
        >
          {notice}
        </p>
      )}

      <section className="rounded-xl border border-slate-100 bg-white p-5 shadow-sm">
        <div className="mb-3 flex flex-wrap items-center justify-between gap-2">
          <div>
            <h2 className="text-sm font-semibold text-slate-800">Manuscript progress</h2>
            <p className="mt-0.5 text-xs text-slate-500">
              {formatNumber(totalWords)} / {formatNumber(TARGET_WORDS)} words · {REFERENCE_COUNT}{' '}
              references · 12 figures (fixture metadata)
            </p>
          </div>
          <div className="text-right">
            <p className="text-2xl font-black text-slate-900">{progress}%</p>
            <p className="text-xs text-slate-400">of word target</p>
          </div>
        </div>
        <div
          className="h-2.5 overflow-hidden rounded-full bg-slate-100"
          role="progressbar"
          aria-valuenow={progress}
          aria-valuemin={0}
          aria-valuemax={100}
          aria-label="Manuscript word target progress"
        >
          <div
            className="h-full rounded-full bg-gradient-to-r from-blue-500 to-cyan-500 transition-all"
            style={{ width: `${progress}%` }}
          />
        </div>
      </section>

      <div className="grid grid-cols-1 gap-6 lg:grid-cols-3">
        <div className="space-y-4 lg:col-span-1">
          <section aria-labelledby="sections-heading">
            <h2
              id="sections-heading"
              className="mb-3 text-xs font-semibold uppercase tracking-wider text-slate-500"
            >
              Sections
            </h2>
            <ul className="space-y-1">
              {sections.map((section) => {
                const isActive = section.id === activeSection?.id;
                return (
                  <li key={section.id}>
                    <button
                      type="button"
                      onClick={() => setActiveSectionId(section.id)}
                      aria-pressed={isActive}
                      className={`flex w-full items-center justify-between gap-2 rounded-lg px-3 py-2.5 text-sm transition-all ${
                        isActive
                          ? 'border border-blue-200 bg-blue-50 text-blue-700'
                          : 'text-slate-600 hover:bg-slate-100'
                      }`}
                    >
                      <span className="flex-1 truncate text-left font-medium">{section.label}</span>
                      <span className="flex shrink-0 items-center gap-2">
                        {section.wordCount > 0 && (
                          <span className="text-xs text-slate-400">{section.wordCount}w</span>
                        )}
                        <span
                          className={`rounded-full px-1.5 py-0.5 text-xs ${statusStyles[section.status]}`}
                          title={section.status.replace('_', ' ')}
                        >
                          <span aria-hidden="true">{statusIcons[section.status]}</span>
                          <span className="sr-only">{section.status.replace('_', ' ')}</span>
                        </span>
                      </span>
                    </button>
                  </li>
                );
              })}
            </ul>
          </section>

          <section className="rounded-xl border border-slate-100 bg-white p-4 shadow-sm">
            <h2 className="mb-3 text-xs font-semibold text-slate-700">📋 AIAA compliance checks</h2>
            <ul className="space-y-2">
              {compliance.map((item) => (
                <li key={item.label} className="flex items-start gap-2">
                  <span
                    className={`mt-0.5 flex h-4 w-4 shrink-0 items-center justify-center rounded-full text-xs ${
                      item.ok ? 'bg-emerald-100 text-emerald-700' : 'bg-amber-100 text-amber-700'
                    }`}
                    aria-hidden="true"
                  >
                    {item.ok ? '✓' : '!'}
                  </span>
                  <div className="min-w-0">
                    <p className="text-xs text-slate-600">{item.label}</p>
                    <p className="text-xs text-slate-400">{item.detail}</p>
                  </div>
                </li>
              ))}
            </ul>
          </section>
        </div>

        <div className="lg:col-span-2">
          {showLatex ? (
            <section className="overflow-hidden rounded-xl bg-slate-900">
              <div className="flex flex-wrap items-center justify-between gap-2 border-b border-slate-700 px-4 py-2.5">
                <span className="font-mono text-xs text-slate-400">
                  manuscript.tex — AIAA template
                </span>
                <div className="flex gap-3">
                  <button
                    type="button"
                    onClick={copyLatex}
                    className="text-xs text-slate-300 hover:text-white"
                  >
                    Copy
                  </button>
                  <button
                    type="button"
                    onClick={downloadLatex}
                    className="text-xs text-slate-300 hover:text-white"
                  >
                    Download
                  </button>
                  <button
                    type="button"
                    onClick={() => setShowLatex(false)}
                    className="text-xs text-slate-400 hover:text-white"
                  >
                    Close
                  </button>
                </div>
              </div>
              <pre className="max-h-[600px] overflow-auto whitespace-pre-wrap p-5 font-mono text-xs leading-relaxed text-emerald-300">
                {latex}
              </pre>
            </section>
          ) : (
            <section className="overflow-hidden rounded-xl border border-slate-100 bg-white shadow-sm">
              <div className="flex flex-wrap items-center justify-between gap-2 border-b border-slate-100 px-4 py-4 sm:px-6">
                <div>
                  <h2 className="font-semibold text-slate-800">{activeSection?.label}</h2>
                  <p className="mt-0.5 text-xs text-slate-400">{activeSection?.wordCount} words</p>
                </div>
                <span
                  className={`rounded-full px-2 py-1 text-xs font-medium ${
                    statusStyles[activeSection?.status ?? 'pending']
                  }`}
                >
                  {activeSection?.status.replace('_', ' ')}
                </span>
              </div>
              <div className="max-h-[580px] overflow-y-auto p-4 sm:p-6">
                {activeSection?.content ? (
                  <div className="whitespace-pre-wrap font-serif text-sm leading-relaxed text-slate-700">
                    {activeSection.content}
                  </div>
                ) : (
                  <p className="py-16 text-center text-sm text-slate-500">
                    No content for this section yet.
                  </p>
                )}
              </div>
            </section>
          )}
        </div>
      </div>
    </div>
  );
}
